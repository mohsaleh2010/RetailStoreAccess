def cs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'


# ------------------------------------------------------------------ Access expression -> C#
_TOKEN = re.compile(r'\s*(\[[^\]]+\]|"(?:[^"]|"")*"|\d+(?:\.\d+)?|[A-Za-z_]\w*|<>|>=|<=|[-+*/&=<>(),])')


def _tokens(expr: str) -> List[str]:
    out, pos = [], 0
    while pos < len(expr):
        m = _TOKEN.match(expr, pos)
        if not m:
            if expr[pos:].strip() == "":
                break
            raise ValueError(f"cannot read {expr!r} at {pos}")
        out.append(m.group(1))
        pos = m.end()
    return out


class _Parser:
    """A tree of the expression: ("field", name) ("str", text) ("num", text) ("null",) ("true",) ("call", name, args)
    ("op", op, left, right) ("neg", x)."""

    def __init__(self, expr: str):
        self.t = _tokens(expr)
        self.i = 0

    def peek(self):
        return self.t[self.i] if self.i < len(self.t) else None

    def take(self, want=None):
        tok = self.peek()
        if want is not None and tok != want:
            raise ValueError(f"expected {want!r}, got {tok!r}")
        self.i += 1
        return tok

    def parse(self):
        node = self.concat()
        if self.peek() is not None:
            raise ValueError(f"unexpected {self.peek()!r}")
        return node

    def concat(self):
        node = self.compare()
        while self.peek() == "&":
            self.take()
            node = ("op", "&", node, self.compare())
        return node

    def compare(self):
        node = self.add()
        if self.peek() in ("=", "<>", ">", "<", ">=", "<="):
            op = self.take()
            node = ("op", op, node, self.add())
        return node

    def add(self):
        node = self.mul()
        while self.peek() in ("+", "-"):
            op = self.take()
            node = ("op", op, node, self.mul())
        return node

    def mul(self):
        node = self.unary()
        while self.peek() in ("*", "/"):
            op = self.take()
            node = ("op", op, node, self.unary())
        return node

    def unary(self):
        if self.peek() == "-":
            self.take()
            return ("neg", self.unary())
        return self.primary()

    def primary(self):
        tok = self.take()
        if tok is None:
            raise ValueError("unexpected end")
        if tok == "(":
            node = self.concat()
            self.take(")")
            return node
        if tok.startswith("["):
            return ("field", tok[1:-1])
        if tok.startswith('"'):
            return ("str", tok[1:-1].replace('""', '"'))
        if tok[0].isdigit():
            return ("num", tok)
        if tok == "Null":
            return ("null",)
        if tok == "True":
            return ("true",)
        if self.peek() == "(":
            self.take("(")
            args = []
            if self.peek() != ")":
                args.append(self.concat())
                while self.peek() == ",":
                    self.take()
                    args.append(self.concat())
            self.take(")")
            return ("call", tok, args)
        raise ValueError(f"unknown name {tok!r}")


def _kind(node) -> str:
    """num, text, bool or obj: what the node gives."""
    k = node[0]
    if k in ("num", "neg"):
        return "num"
    if k == "str":
        return "text"
    if k in ("null", "field"):
        return "obj"
    if k == "true":
        return "bool"
    if k == "op":
        if node[1] == "&":
            return "text"
        if node[1] in ("=", "<>", ">", "<", ">=", "<="):
            return "bool"
        return "num"
    name = node[1]
    if name in ("GDate", "Space", "Format"):
        return "text"
    if name == "Sum":
        return "num"
    if name == "IIf":
        kinds = {_kind(node[2][1]), _kind(node[2][2])} - {"obj"}
        if len(kinds) == 1 and not any(n[0] in ("null", "field") for n in node[2][1:]):
            return kinds.pop()
        return "obj"
    return "obj"


def _cs(node, want: str) -> str:
    """C# for the node, as a value of the wanted kind (num = decimal, text = string, bool, obj = object?)."""
    k = node[0]
    if k == "field":
        return {"num": f'r.Num({cs_str(node[1])})', "text": f'r.Text({cs_str(node[1])})',
                "bool": f'r.Bool({cs_str(node[1])})', "obj": f'r.Value({cs_str(node[1])})'}[want]
    if k == "num":
        return {"num": f"{node[1]}m", "obj": f"(object){node[1]}m", "text": cs_str(node[1])}[want]
    if k == "str":
        if want not in ("text", "obj"):
            raise ValueError("a text where a number is wanted")
        return cs_str(node[1])
    if k == "null":
        if want != "obj":
            raise ValueError("Null where a value is wanted")
        return "null"
    if k == "true":
        return "true"
    if k == "neg":
        return _box(f"(-{_cs(node[1], 'num')})", "num", want)
    if k == "op":
        op, a, b = node[1], node[2], node[3]
        if op == "&":
            return f"({_cs(a, 'text')} + {_cs(b, 'text')})"
        if op in ("=", "<>", ">", "<", ">=", "<="):
            cs_op = {"=": "==", "<>": "!="}.get(op, op)
            if "text" in (_kind(a), _kind(b)):
                if op not in ("=", "<>"):
                    raise ValueError("text compared by order")
                code = f"({_cs(a, 'text')} {cs_op} {_cs(b, 'text')})"
            else:
                code = f"({_cs(a, 'num')} {cs_op} {_cs(b, 'num')})"
            return _box(code, "bool", want)
        if op == "/":
            return _box(f"ReportRow.Divide({_cs(a, 'num')}, {_cs(b, 'num')})", "num", want)
        return _box(f"({_cs(a, 'num')} {op} {_cs(b, 'num')})", "num", want)
    name, args = node[1], node[2]
    if name == "GDate":
        with_time = len(args) > 1
        if with_time and args[1][0] != "true":
            raise ValueError("GDate(x, True) only")
        return _box(f"ReportRow.GDate({_cs(args[0], 'obj')}, {'true' if with_time else 'false'})", "text", want)
    if name == "Space":
        return _box(f"ReportRow.Space({_cs(args[0], 'num')})", "text", want)
    if name == "Format":
        if args[1][0] != "str":
            raise ValueError("Format with a fixed pattern only")
        return _box(f"ReportRow.Format({_cs(args[0], 'obj')}, {cs_str(args[1][1])})", "text", want)
    if name == "Nz":
        return _box(f"({_cs(args[0], 'obj')} ?? {_cs(args[1], 'obj')})", "obj", want)
    if name == "IIf":
        cond = _cs(args[0], "bool")
        inner = want if want != "bool" else "bool"
        if want == "obj" and _kind(node) != "obj":
            inner = _kind(node)
            return _box(f"({cond} ? {_cs(args[1], inner)} : {_cs(args[2], inner)})", inner, want)
        return f"({cond} ? {_cs(args[1], inner)} : {_cs(args[2], inner)})"
    raise ValueError(f"unknown function {name}")


def _box(code: str, have: str, want: str) -> str:
    if have == want:
        return code
    if want == "obj":
        return f"(object){code}"
    if want == "text" and have == "num":
        return f"ReportRow.NumberText({code})"
    raise ValueError(f"a {have} where a {want} is wanted: {code}")


def column_lambda(source: str) -> str:
    """The value of a column: a field, or an Access expression ("=...")."""
    if not source.startswith("="):
        return f"r => r.Value({cs_str(source)})"
    return f"r => {_cs(_Parser(source[1:]).parse(), 'obj')}"


def sum_lambda(expr: str) -> str:
    """A summary row "=Sum(x)" over the rows of the report."""
    node = _Parser(expr[1:]).parse()
    if node[0] != "call" or node[1] != "Sum" or len(node[2]) != 1:
        raise ValueError(f"a summary is Sum(...): {expr}")
    return f"rows => rows.Sum(r => {_cs(node[2][0], 'num')})"


def expression_texts(source: str) -> List[str]:
    """The Arabic texts an expression shows (they need English)."""
    if not source.startswith("="):
        return []
    return [s for s in re.findall(r'"((?:[^"]|"")*)"', source) if i18n.has_arabic(s)]


# ------------------------------------------------------------------ the catalogue
def specs():
    lists = {s.key: s for s in RC.LIST_SPECS + WEB_ONLY_SPECS}
    cards = {c.key: c for c in RC.CARD_SPECS}
    return lists, cards


def report_strings() -> List[str]:
    lists, cards = specs()
    out = [g for g, _ in F.REPORT_GROUPS]
    for r in F.REPORTS:
        out.append(r.title)
        if r.key in lists:
            s = lists[r.key]
            out.append(s.no_data)
            for c in s.cols:
                out.append(c.caption)
                out += expression_texts(c.source)
            out += [cap for cap, _ in (s.summary or [])]
        if r.key in cards:
            c = cards[r.key]
            out += [cap for cap, _, _, _ in c.rows] + ([c.note] if c.note else [])
    return [x for x in out if i18n.has_arabic(x)]


def _column(c: RC.Col) -> str:
    return (f"new({cs_str(c.caption)}, {cs_str(FORMATS[c.fmt])}, {'true' if c.total else 'false'}, "
            f"{'true' if c.running else 'false'}, {column_lambda(c.source)})")


def _report(r: F.ReportEntry, lists, cards) -> str:
    link = LINKS.get(r.key)
    cols, sorts, summary, card, no_data, note = "[]", "[]", "[]", "[]", RC.NO_DATA, ""
    if r.key in lists:
        s = lists[r.key]
        cols = "[\n                " + ",\n                ".join(_column(c) for c in s.cols) + "]"
        sorts = "[" + ", ".join(f"({cs_str(f)}, {'true' if d else 'false'})" for f, d in s.sorts) + "]"
        summary = "[" + ", ".join(f"new({cs_str(cap)}, {sum_lambda(e)})" for cap, e in (s.summary or [])) + "]"
        no_data = s.no_data
    elif r.key in cards:
        c = cards[r.key]
        card = "[\n                " + ",\n                ".join(
            f"new({cs_str(cap)}, {cs_str(FORMATS[fmt])}, {'true' if bold else 'false'}, {column_lambda(src)})"
            for cap, src, fmt, bold in c.rows) + "]"
        note = c.note
    elif not link:
        raise ValueError(f"report {r.key} has no layout for the web")
    return (f"        new({cs_str(r.key)}, {cs_str(r.title)}, {cs_str(r.query)}, {cs_str(r.needs)}, {cs_str(r.date_column)}, "
            f"{cs_str(link or '')}, {cs_str(no_data)}, {cs_str(note)},\n            {cols},\n            {sorts}, {summary},\n"
            f"            {card})")


def build_reports() -> str:
    lists, cards = specs()
    body = ",\n".join(_report(r, lists, cards) for r in F.REPORTS)
    order = [r.key for r in F.REPORTS]
    grouped = sorted(k for _, keys in F.REPORT_GROUPS for k in keys)
    if grouped != sorted(order):
        raise ValueError("forms.REPORT_GROUPS must hold every report of forms.REPORTS once")
    groups = ",\n".join(
        f"        ({cs_str(g)}, [" + ", ".join(cs_str(k) for k in order if k in keys) + "])"
        for g, keys in F.REPORT_GROUPS)
    return f"""{HEADER}#nullable enable
namespace RetailStore.Data.Reports;

/// <summary>The report centre of Access (forms.REPORTS = modAppData.ReportRow) with the layouts of its reports
/// (tools/reports_catalog.py), in the order of frmReportCenter.</summary>
public static partial class ReportCatalog
{{
    public static readonly IReadOnlyList<ReportDef> All =
    [
{body}
    ];

    /// <summary>The groups of the report centre on the web (forms.REPORT_GROUPS): each report in one group, in the order of All.</summary>
    public static readonly IReadOnlyList<(string Group, string[] Keys)> Groups =
    [
{groups}
    ];
}}
"""


def build_saved_queries() -> str:
    rows = "\n".join(f"        ({cs_str(q.name)}, {cs_str(i18n.resolve_names(q.sql, False).strip())}),"
                     for q in Q.QUERIES)
    return f"""{HEADER}namespace RetailStore.Data.Reports;

/// <summary>The saved queries of Access (tools/queries.py) as SQLite views, in the order they are created: the
/// development and test database runs the very SQL of Access (SavedQueryRunner registers its functions).</summary>
public static partial class SavedQueries
{{
    public static readonly (string Name, string Sql)[] Views =
    [
{rows}
    ];
}}
"""


