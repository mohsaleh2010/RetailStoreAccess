def build_vectors() -> str:
    pw = "\n".join(f"        ({cs_str(p)}, {cs_str(s)}, {cs_str(SEC.password_hash(p, s))}),"
                   for p, s in SEC.PASSWORD_VECTORS)
    sha = "\n".join(f"        ({cs_str(t)}, {cs_str(SEC.sha256_hex(t.encode('utf-8')))}),"
                    for t in SEC.SHA_VECTORS if len(t) < 100)
