def _value_list(rows: str) -> Optional[List[Tuple[str, str]]]:
    if not rows or rows.lstrip().upper().startswith("SELECT"):
        return None
    parts = rows.split(";")
    return [(parts[i], parts[i + 1]) for i in range(0, len(parts) - 1, 2)]


def name_fields(tname: str) -> Tuple[str, Optional[str]]:
    """The Arabic and English name fields shown for a row of a look-up table."""
    if tname in master_en.ENGLISH_NAMES:
        en, ar, _key, _names = master_en.ENGLISH_NAMES[tname]
        return ar, en
    return {"Employees": ("EmployeeName", None), "Currencies": ("CurrencyName", None)}[tname]


def rule_limits(f: Field) -> Dict[str, object]:
    """The simple Access rules of a field as limits the web checks (others stay in code: Like, Len)."""
    r = (f.rule or "").strip()
    out: Dict[str, object] = {}
    if not r:
        return out
    m = re.fullmatch(r'In \((.*)\)', r)
    if m:
        out["allowed"] = [s.strip().strip('"') for s in m.group(1).split(",")]
        return out
    m = re.fullmatch(r"Between (-?[\d.]+) And (-?[\d.]+)", r)
    if m:
        return {"min": m.group(1), "max": m.group(2)}
    for part in r.split(" And "):
        m = re.fullmatch(r"(>=|>|<=|<)(-?[\d.]+)", part.strip())
        if not m:
            return {}                           # Like, Len(), <>: checked by the screen's own rules
        op, n = m.groups()
        if op == ">=":
            out["min"] = n
        elif op == ">":
            out["min"], out["minExclusive"] = n, True
        elif op == "<=":
            out["max"] = n
        else:
            out["max"], out["maxExclusive"] = n, True
    return out


KIND = {"TEXT": "Text", "MEMO": "Memo", "MONEY": "Money", "QTY": "Quantity", "RATE": "Rate", "INT": "Integer",
        "LONG": "Integer", "BYTE": "Integer", "BOOL": "Bool", "DATE": "Date", "DATETIME": "DateTime"}
CONVERT = {"string": "Text", "string?": "TextN", "int": "Int", "int?": "IntN", "short": "Short", "short?": "ShortN",
           "byte": "Byte", "byte?": "ByteN", "decimal": "Decimal", "decimal?": "DecimalN", "bool": "Bool",
           "DateTime": "Date", "DateTime?": "DateN"}


def _list_columns(s: F.DataScreen, fld_by_name) -> List[Tuple[str, str, float]]:
    """(header, field, width) from list_select: the first field of each column expression."""
    items, depth, cur = [], 0, ""
    for ch in s.list_select:
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            items.append(cur)
            cur = ""
        else:
            cur += ch
    items.append(cur)
    out = []
    for expr, (header, width) in zip(items, s.list_headers):
        field = re.search(r"\bt\.(\w+)", expr).group(1)
        out.append((header, field, width))
    return out


def _field_spec(s: F.DataScreen, t: Table, item) -> str:
    if isinstance(item, F.Info):
        text = item.text.strip()
        return f"            new FieldSpec<{t.name}> {{ Name = {cs_str(item.name)}, Kind = FieldKind.Info, Label = {cs_str(text)} }},"
    f = next(x for x in t.fields if x.name == item.field)
    seq_field = s.seq.split(":")[1] if s.seq else ""
    kind = KIND[f.kind]
    lookup = "null"
    options = _value_list(item.rows)
    if options:
        kind = "Choice"
    elif f.fk:
        parent, key = f.fk.split(".")
        ar, en = name_fields(parent)
        kind = "Lookup"
        lookup = f'new LookupSpec("{parent}", "{key}", "{ar}", {cs_str(en) if en else "null"})'
    elif item.rows:
        raise ValueError(f"{s.name}.{f.name}: a combo without a foreign key or a value list")
    lim = rule_limits(f)
    allowed = lim.get("allowed")
    if allowed and options and set(allowed) != {k for k, _ in options}:
        raise ValueError(f"{s.name}.{f.name}: the value list differs from the rule")
    props = [f"Name = {cs_str(f.name)}", f"Kind = FieldKind.{kind}", f"Label = {cs_str(item.label or f.caption)}",
             f"Caption = {cs_str(f.caption)}"]
    if item.hint:
        props.append(f"Hint = {cs_str(item.hint)}")
    if item.span != 1:
        props.append(f"Span = {item.span}")
    if item.locked:
        props.append("Locked = true")
    if f.required and f.kind not in ("AUTO", "BOOL") and f.name != seq_field:
        props.append("Required = true")
    if f.kind == "TEXT":
        props.append(f"MaxLength = {f.size}")
    if "min" in lim:
        props.append(f"Min = {lim['min']}m")
        if lim.get("minExclusive"):
            props.append("MinExclusive = true")
    if "max" in lim:
        props.append(f"Max = {lim['max']}m")
        if lim.get("maxExclusive"):
            props.append("MaxExclusive = true")
    if options:
        props.append("Options = [" + ", ".join(f"new({cs_str(k)}, {cs_str(v)})" for k, v in options) + "]")
    elif allowed:
        props.append("Options = [" + ", ".join(f"new({cs_str(k)}, {cs_str(k)})" for k in allowed) + "]")
    if lookup != "null":
        props.append(f"Lookup = {lookup}")
    ct = clr_type(f)
    props.append(f"Get = e => e.{ident(f.name)}")
    props.append(f"Set = (e, v) => e.{ident(f.name)} = ValueConvert.{CONVERT[ct]}(v)")
    return f"            new FieldSpec<{t.name}> {{ {', '.join(props)} }},"


def _screen_spec(route: str, s: F.DataScreen) -> str:
    t = table(s.table)
    fld_by_name = {f.name: f for f in t.fields}
    cols = _list_columns(s, fld_by_name)
    name_ar, name_en = name_fields(t.name) if t.name in master_en.ENGLISH_NAMES else (None, None)
    order = re.fullmatch(r"t\.(\w+)", s.list_order).group(1)
    active = s.active.split(".")[1] if s.active else None
    seq = s.seq.split(":") if s.seq else None
    lines = [f"    public static readonly ScreenSpec<{t.name}> {t.name} = new()", "    {",
             f'        Name = "{s.name}", Table = "{t.name}", Key = "{s.pk}", Route = "{route}", Icon = "{s.icon}",',
             f"        Caption = {cs_str(s.caption)}, Subtitle = {cs_str(s.subtitle)},",
             f"        KeyOf = e => e.{ident(s.pk)},",
             f"        FindAsync = (db, id) => db.{t.name}.FirstOrDefaultAsync(e => e.{ident(s.pk)} == (int)id),",
             f"        Query = db => db.{t.name},",
             f"        OrderBy = q => q.OrderBy(e => e.{ident(order)}),",
             "        Search = [" + ", ".join(cs_str(re.sub(r"^t\.", "", x)) for x in s.search) + "],"]
    if active:
        lines.append(f'        ActiveField = "{active}",')
    if seq:
        lines.append(f'        Sequence = "{seq[0]}", SequenceField = "{seq[1]}",')
    if s.unique:
        lines.append("        Unique = [" + ", ".join(cs_str(u) for u in s.unique) + "],")
    if name_ar:
        lines.append(f'        NameField = "{name_ar}", NameEnField = "{name_en}",')
    lines.append("        Columns = [" + ", ".join(
        f"new({cs_str(h)}, {cs_str(fld)}, {w}m)" for h, fld, w in cols) + "],")
    lines.append("        Fields =\n        [")
    lines += [_field_spec(s, t, item) for item in s.fields]
    lines.append("        ],")
    lines.append("    };")
    return "\n".join(lines)


def web_screens() -> List[Tuple[str, F.DataScreen]]:
    by_name = {s.name: s for s in F.DATA_SCREENS}
    return [(route, by_name[name]) for route, name in WEB_SCREENS]


def lookup_tables() -> List[str]:
    out = []
    for _route, s in web_screens():
        t = table(s.table)
        for item in s.fields:
            if isinstance(item, F.Fld) and not _value_list(item.rows):
                f = next(x for x in t.fields if x.name == item.field)
                if f.fk and f.fk.split(".")[0] not in out:
                    out.append(f.fk.split(".")[0])
    return out


def _lookup_case(tname: str) -> str:
    t = table(tname)
    key = t.pk[0]
    ar, en = name_fields(tname)
    has_active = any(f.name == "IsActive" for f in t.fields)
    text = f"english ? (x.{en} ?? x.{ar}) : x.{ar}" if en else f"x.{ar}"
    if tname == "Currencies":
        text = f'x.{key} + "  " + x.{ar}'
    active = "x.IsActive" if has_active else "true"
    return (f'            "{tname}" => await db.{tname}.AsNoTracking().OrderBy(x => x.{ar})\n'
            f"                .Select(x => new LookupItem(x.{key}, {text}, {active})).ToListAsync(),")


