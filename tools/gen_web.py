def ident(name: str) -> str:
    return "@" + name if name in CS_KEYWORDS else name


def cs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n") + '"'


def nullable(f: Field) -> bool:
    """A field that may hold Null: not required and not Yes/No (the SQL Server script: NOT NULL only for those)."""
    return f.kind not in ("AUTO", "BOOL") and not f.required


def clr_type(f: Field) -> str:
    t = CLR[f.kind]
    return t + "?" if nullable(f) else t


def default_literal(f: Field) -> Optional[str]:
    """The Access default as a C# initializer (None = the type's own)."""
    d = (f.default or "").strip()
    if f.kind == "BOOL":
        return "true" if d.lower() == "true" else None
    if not d or f.kind == "AUTO":
        if f.kind in ("TEXT", "MEMO") and not nullable(f):
            return '""'
        return None
    if d == "Now()":
        return "DateTime.Now"
    if d == "Date()":
        return "DateTime.Today"
    if re.fullmatch(r'"[^"]*"', d):
        return cs_str(d[1:-1])
    if re.fullmatch(r"-?\d+(\.\d+)?", d):
        if f.kind in ("MONEY", "QTY", "RATE"):
            return d + "m"
        if f.kind in ("INT", "BYTE"):
            return f"({CLR[f.kind]}){d}"
        return d
    raise ValueError(f"default not translated: {f.name} = {d}")


def entity_class(t: Table) -> str:
    out = [f"/// <summary>{esc_xml(t.caption)}: {esc_xml(t.purpose)}</summary>",
           f"public partial class {t.name}", "{"]
    for f in t.fields:
        if f.name == t.name:
            raise ValueError(f"a field may not have the name of its table: {t.name}.{f.name}")
        init = default_literal(f)
        line = f"    public {clr_type(f)} {ident(f.name)} {{ get; set; }}"
        if init:
            line += f" = {init};"
        out.append(f"    /// <summary>{esc_xml(f.caption)}</summary>")
        out.append(line)
    out.append("}")
    return "\n".join(out)


def esc_xml(s: str) -> str:
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")


def build_entities() -> str:
    parts = [HEADER, "#nullable enable", "namespace RetailStore.Data.Entities;", ""]
    parts += [entity_class(t) + "\n" for t in TABLES]
    return "\n".join(parts)


def _model_entity(t: Table, rels: List[R.Relation]) -> str:
    x = "x"
    out = [f"        b.Entity<{t.name}>(e =>", "        {", f'            e.ToTable("{t.name}");']
    keys = ", ".join(f"{x}.{ident(k)}" for k in t.pk)
    out.append(f"            e.HasKey({x} => " + (f"new {{ {keys} }}" if len(t.pk) > 1 else keys) + ");")
    for f in t.fields:
        p = f"e.Property({x} => {x}.{ident(f.name)})"
        if f.kind == "AUTO":
            out.append(f"            {p}.ValueGeneratedOnAdd();")
        elif f.kind in ("TEXT", "MEMO"):
            line = p + (f".HasMaxLength({f.size})" if f.kind == "TEXT" else "")
            line += ".IsRequired()" if not nullable(f) else ""
            if line != p:
                out.append(f"            {line};")
        if f.kind in ("MONEY", "QTY", "RATE"):
            out.append(f'            if (sqlServer) {p}.HasColumnType("money"); else {p}.HasPrecision(19, 4);')
    for i in t.indexes:
        if i.primary:
            continue
        cols = ", ".join(f"{x}.{ident(c)}" for c in i.fields)
        cols = f"new {{ {cols} }}" if len(i.fields) > 1 else cols
        out.append(f'            if (!sqlServer) e.HasIndex({x} => {cols}).HasDatabaseName("{t.name}_{i.name}")'
                   + (".IsUnique()" if i.unique else "") + ";")
    for r in rels:
        if r.child != t.name:
            continue
        delete = "Cascade" if r.cascade_delete else ("Restrict" if r.required else "ClientSetNull")
        principal = "" if table(r.parent).pk == [r.parent_field] else \
            f".HasPrincipalKey(p => p.{ident(r.parent_field)})"
        out.append(f"            e.HasOne<{r.parent}>().WithMany(){principal}.HasForeignKey({x} => {x}.{ident(r.child_field)})"
                   f'.HasConstraintName("{r.name}").OnDelete(DeleteBehavior.{delete});')
    out.append('            if (sqlServer) e.Property<byte[]>("RowVer").IsRowVersion();')
    out.append("        });")
    return "\n".join(out)


